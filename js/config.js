// すべてのピース（回転を含む）を生成
const ALL_PIECES = (function () {
    const res = [];
    BASE_SHAPES.forEach(sh => {
        let curr = sh;
        for (let i = 0; i < 4; i++) {
            if (!res.some(s => JSON.stringify(s) === JSON.stringify(curr))) res.push(curr);
            const r = curr.length, c = curr[0].length;
            const next = Array.from({ length: c }, () => Array(r).fill(0));
            for (let y = 0; y < r; y++) {
                for (let x = 0; x < c; x++) {
                    next[x][r - 1 - y] = curr[y][x];
                }
            }
            curr = next;
        }
    });
    return res;
})();
